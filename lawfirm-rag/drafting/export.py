"""Draft export: DOCX (python-docx), Markdown and plain text.

Renders a grounded draft as a title + per-section headings and prose, with each
section's citations gathered into a trailing ``Endnotes`` list. python-docx has
no native endnote API, so the sources are emitted as a clearly-labelled
end-of-document appendix (the same information a Word endnote would carry). A
footer on every page carries the draft status and a standing disclaimer.

Pure functions over a draft dict (as returned by ``drafting.store.get_draft``):
no I/O, no network — safe to unit-test offline.
"""
from __future__ import annotations

import re
from io import BytesIO
from typing import Any

from docx import Document
from docx.shared import Pt

DRAFT_DISCLAIMER = (
    "DRAFT — generated by the firm's drafting assistant from the authorized "
    "document repository and clause bank. Not legal advice; review before use."
)


def _sections(draft: dict[str, Any]) -> list[dict[str, Any]]:
    sections = draft.get("sections") or []
    return sorted(sections, key=lambda s: s.get("order_index", 0))


def _paragraphs(content: str | None) -> list[str]:
    return [part.strip() for part in re.split(r"\n\s*\n", content or "") if part.strip()]


def _meta_line(draft: dict[str, Any]) -> str:
    doc_type = str(draft.get("doc_type") or "").replace("_", " ")
    status = str(draft.get("status") or "draft")
    version = draft.get("current_version", 1)
    parts = [p for p in (doc_type, status, f"v{version}") if p]
    return " · ".join(parts)


def _source_line(source: dict[str, Any]) -> str:
    title = source.get("title") or source.get("file_title") or "Unknown source"
    detail = source.get("section_heading") or source.get("url") or source.get("file_id") or ""
    return f"{title} — {detail}" if detail else str(title)


def _iter_endnotes(draft: dict[str, Any]):
    for section in _sections(draft):
        sources = section.get("sources") or []
        if sources:
            yield section, sources


def build_docx(draft: dict[str, Any]) -> bytes:
    """Render ``draft`` as a .docx and return the file bytes."""
    document = Document()
    document.add_heading(draft.get("title") or "Untitled draft", level=0)
    document.add_paragraph(_meta_line(draft))

    sections = _sections(draft)
    if not sections:
        document.add_paragraph("This draft has no sections.")
    for section in sections:
        document.add_heading(section.get("heading") or "Untitled section", level=1)
        paragraphs = _paragraphs(section.get("content"))
        if not paragraphs:
            document.add_paragraph("Not generated yet.")
            continue
        for paragraph in paragraphs:
            document.add_paragraph(paragraph)

    if any(True for _ in _iter_endnotes(draft)):
        document.add_heading("Endnotes — sources", level=1)
        for section, sources in _iter_endnotes(draft):
            document.add_heading(section.get("heading") or "Section", level=2)
            for source in sources:
                document.add_paragraph(f"[{source.get('n')}] {_source_line(source)}")

    footer = document.sections[0].footer
    footer_paragraph = footer.paragraphs[0] if footer.paragraphs else footer.add_paragraph()
    footer_paragraph.text = DRAFT_DISCLAIMER
    if footer_paragraph.runs:
        footer_paragraph.runs[0].font.size = Pt(8)

    buffer = BytesIO()
    document.save(buffer)
    return buffer.getvalue()


def build_markdown(draft: dict[str, Any]) -> str:
    lines = [f"# {draft.get('title') or 'Untitled draft'}", "", f"_{_meta_line(draft)}_", ""]
    for section in _sections(draft):
        lines.append(f"## {section.get('heading') or 'Untitled section'}")
        lines.append("")
        content = (section.get("content") or "").strip()
        lines.append(content or "_Not generated yet._")
        lines.append("")
    if any(True for _ in _iter_endnotes(draft)):
        lines.append("## Endnotes — sources")
        lines.append("")
        for section, sources in _iter_endnotes(draft):
            lines.append(f"**{section.get('heading') or 'Section'}**")
            for source in sources:
                lines.append(f"- [{source.get('n')}] {_source_line(source)}")
            lines.append("")
    lines.append("---")
    lines.append(f"_{DRAFT_DISCLAIMER}_")
    return "\n".join(lines)


def build_text(draft: dict[str, Any]) -> str:
    lines = [str(draft.get("title") or "Untitled draft"), _meta_line(draft), ""]
    for section in _sections(draft):
        lines.append(str(section.get("heading") or "Untitled section").upper())
        lines.append((section.get("content") or "Not generated yet.").strip())
        lines.append("")
    if any(True for _ in _iter_endnotes(draft)):
        lines.append("ENDNOTES - SOURCES")
        for section, sources in _iter_endnotes(draft):
            lines.append(section.get("heading") or "Section")
            for source in sources:
                lines.append(f"  [{source.get('n')}] {_source_line(source)}")
        lines.append("")
    lines.append(DRAFT_DISCLAIMER)
    return "\n".join(lines)
